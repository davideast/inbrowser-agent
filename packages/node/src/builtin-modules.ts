// Node excludes these names from builtinModules because their prefix is required.
const prefixedOnly = new Set(['test', 'test/reporters', 'sea', 'sqlite']);
const names = new Set(builtinModules);
export function isBuiltin(value: unknown): boolean {
  if (typeof value !== 'string') return false;
  if (!value.startsWith('node:')) return names.has(value);
  const name = value.slice(5);
  return names.has(name) || prefixedOnly.has(name);
}
